/**
 * Sitemap generation.
 *
 * The nine pre-existing URLs stay exactly as they are in public/sitemap.xml
 * — this script never rewrites them. It appends:
 *
 *   /blog/                     always
 *   /blog/<slug>               published articles only, newest first
 *
 * Drafts can never appear: the source is getPublishedPosts(), which filters
 * on status === "published". A final assertion fails the build if any draft
 * slug shows up in the output.
 *
 * Output goes to dist/sitemap.xml (what Vercel serves). public/sitemap.xml
 * remains the committed source of truth for the non-blog URLs.
 *
 * Run standalone: npm run sitemap
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { getPublishedPosts } from "../src/data/blogPosts.js";
import { draftPosts } from "../src/data/blogDrafts.js";
import { SITE_URL, BLOG_URL } from "../src/lib/siteConfig.js";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

const escapeXml = (value) =>
  String(value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");

function urlEntry({ loc, lastmod, changefreq, priority }) {
  return [
    "  <url>",
    `    <loc>${escapeXml(loc)}</loc>`,
    lastmod ? `    <lastmod>${lastmod}</lastmod>` : null,
    changefreq ? `    <changefreq>${changefreq}</changefreq>` : null,
    priority ? `    <priority>${priority}</priority>` : null,
    "  </url>",
  ]
    .filter(Boolean)
    .join("\n");
}

/** Remove any blog URL already present so the generator is idempotent. */
function stripExistingBlogUrls(xml) {
  return xml.replace(
    new RegExp(
      `\\s*<url>\\s*<loc>${SITE_URL.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}/blog[^<]*</loc>[\\s\\S]*?</url>`,
      "g"
    ),
    ""
  );
}

/**
 * @param {{ today?: string, outFile?: string }} options
 * @returns {Promise<{urls: string[], outFile: string}>}
 */
export async function generateSitemap({ today, outFile } = {}) {
  const buildDate = today || new Date().toISOString().slice(0, 10);
  const basePath = path.join(ROOT, "public", "sitemap.xml");
  const destination = outFile || path.join(ROOT, "dist", "sitemap.xml");

  const baseXml = await readFile(basePath, "utf8");
  const stripped = stripExistingBlogUrls(baseXml);

  const posts = getPublishedPosts();

  const blogEntries = [
    urlEntry({
      loc: BLOG_URL,
      lastmod: posts[0]?.updatedAt || posts[0]?.publishedAt || buildDate,
      changefreq: "weekly",
      priority: "0.85",
    }),
    ...posts.map((post) =>
      urlEntry({
        loc: `${SITE_URL}/blog/${post.slug}`,
        lastmod: post.updatedAt || post.publishedAt,
        changefreq: "monthly",
        priority: "0.75",
      })
    ),
  ];

  const output = stripped.replace(
    "</urlset>",
    `\n  <!-- Blog (generated by scripts/generate-sitemap.mjs — published articles only) -->\n${blogEntries.join(
      "\n\n"
    )}\n\n</urlset>`
  );

  // Guard: a draft must never reach the sitemap, no matter what changed above.
  for (const draft of draftPosts) {
    if (output.includes(`/blog/${draft.slug}<`) || output.includes(`/blog/${draft.slug}\n`)) {
      throw new Error(
        `Refusing to write sitemap: draft "${draft.slug}" is present. Drafts must never be published.`
      );
    }
  }

  await writeFile(destination, output, "utf8");

  const locs = [...output.matchAll(/<loc>([^<]+)<\/loc>/g)].map((match) => match[1]);

  return { urls: locs, outFile: destination };
}

const isDirectRun =
  process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (isDirectRun) {
  generateSitemap()
    .then(({ urls, outFile }) => {
      console.log(`[sitemap] wrote ${urls.length} URLs to ${path.relative(ROOT, outFile)}`);
      urls.forEach((url) => console.log(`[sitemap]   ${url}`));
    })
    .catch((error) => {
      console.error(`[sitemap] FAILED: ${error.message}`);
      process.exitCode = 1;
    });
}
